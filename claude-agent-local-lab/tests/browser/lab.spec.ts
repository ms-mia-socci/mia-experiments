import {test,expect} from '@playwright/test';
const origin='http://127.0.0.1:5273';
test('real SDK stream, reload approval, patch, isolation, denial and cancellation',async({page,browser})=>{
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  await page.getByRole('link',{name:'Open the local lab'}).click();
  await page.getByRole('button',{name:'Continue as Mia'}).click();
  await page.getByRole('button',{name:'Find and fix the shipping bug'}).click();
  await expect(page.getByRole('button',{name:'Approve change'})).toBeVisible({timeout:90_000});
  const id=await page.evaluate(()=>localStorage.getItem('poc-thread'));
  const pending=await (await page.request.get(`/api/threads/${id}`)).json();
  expect(pending.events.some((e:any)=>e.type==='TEXT_MESSAGE_CONTENT')).toBeTruthy();
  expect(pending.events.some((e:any)=>e.name==='approval_requested')).toBeTruthy();
  await page.reload();
  await expect(page.getByRole('button',{name:'Approve change'})).toBeVisible();
  await page.screenshot({path:'.local/approval.png',fullPage:true});
  await page.getByRole('button',{name:'Approve change'}).click();
  await expect(page.getByText('All tests passed',{exact:false})).toBeVisible({timeout:90_000});
  await expect(page.locator('.status')).toHaveText('Complete',{timeout:90_000});
  const completed=await (await page.request.get(`/api/threads/${id}`)).json();
  expect(completed.audit.some((a:any)=>a.decision==='approved')).toBeTruthy();
  expect(completed.patch).toContain('+');
  const replay=await page.request.post(`/api/threads/${id}/approval`,{headers:{Origin:origin},data:{id:pending.pendingApproval.id,decision:'approved'}});
  expect(replay.status()).toBe(409);
  const csrf=await page.request.post('/api/threads',{headers:{Origin:'https://untrusted.example'}});expect(csrf.status()).toBe(403);
  await page.getByRole('button',{name:'Events',exact:true}).click();
  await expect(page.getByText('RUN_FINISHED',{exact:true})).toBeVisible();
  await page.screenshot({path:'.local/events.png',fullPage:true});
  await page.getByRole('button',{name:'Changes',exact:true}).click();
  await expect(page.getByRole('link',{name:'Download patch'})).toBeVisible();
  expect((await page.request.get(`/api/threads/${id}/patch`)).status()).toBe(200);
  await page.screenshot({path:'.local/completed.png',fullPage:true});
  const tim=await browser.newContext();const other=await tim.newPage();
  await other.goto(origin+'/auth/login');await other.getByRole('button',{name:'Continue as Tim'}).click();
  expect((await (await other.request.get(origin+'/api/threads')).json()).some((thread:any)=>thread.id===id)).toBeFalsy();
  expect((await other.request.get(origin+`/api/threads/${id}`)).status()).toBe(404);
  expect((await other.request.post(origin+`/api/threads/${id}/approval`,{headers:{Origin:origin},data:{id:pending.pendingApproval.id,decision:'approved'}})).status()).toBe(404);
  await other.getByRole('button',{name:'Find and fix the shipping bug'}).click();
  await expect(other.getByRole('button',{name:'Deny',exact:true})).toBeVisible({timeout:90_000});
  await other.getByRole('button',{name:'Deny',exact:true}).click();
  await expect(other.locator('.status')).toHaveText('Complete',{timeout:90_000});
  const otherId=await other.evaluate(()=>localStorage.getItem('poc-thread'));
  const denied=await (await other.request.get(origin+`/api/threads/${otherId}`)).json();
  expect(denied.patch).toBe('');expect(denied.audit.some((a:any)=>a.decision==='denied')).toBeTruthy();
  await other.getByRole('button',{name:'New conversation'}).click();
  await other.getByRole('button',{name:'Find and fix the shipping bug'}).click();
  await expect(other.getByRole('button',{name:'Approve change'})).toBeVisible({timeout:90_000});
  await other.getByRole('button',{name:'Stop',exact:false}).click();
  await expect(other.getByRole('button',{name:'Approve change'})).not.toBeVisible({timeout:15_000});
  const cancelledId=await other.evaluate(()=>localStorage.getItem('poc-thread'));
  await expect.poll(async()=> (await (await other.request.get(origin+`/api/threads/${cancelledId}`)).json()).status).toBe('cancelled');
  expect(errors).toEqual([]);
  await tim.close();
});
